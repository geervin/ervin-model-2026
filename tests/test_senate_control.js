"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const source=fs.readFileSync("scripts/senate_control.js","utf8");
const ctx={window:{}};vm.runInNewContext(source,ctx);
const project=ctx.window.ERVIN_SENATE_CONTROL.project;
const codes=["ME","MI","OH","TX","IA","KS","MN","AK","GA","NC","NH","NE","SC","MS","FL","SD","MT"];
const all=(v)=>codes.map(code=>({code,margin:v,sigma:5.2}));
const check=x=>{
 assert.equal(x.assumptions.tracked,17);
 assert.equal(x.assumptions.unmodeledSeats,18);
 assert.ok(Math.abs(x.demSeats+x.repSeats+x.otherSeats-100)<1e-9);
 assert.ok(Math.abs(x.partyD+x.partyR+x.uncertain-1)<1e-9);
 assert.ok(x.demRange[0]<=x.demRange[1]&&x.repRange[0]<=x.repRange[1]);
 return x;
};
const republican=check(project(all(-45)));
assert.ok(republican.partyR>.999,"All Republican leads must imply Republican control");
assert.ok(republican.repSeats>56.99);
const democratic=check(project(all(45)));
assert.ok(democratic.partyD>.999,"All non-Republican leads must imply Democratic majority");
assert.ok(democratic.demSeats>56.99);
assert.ok(democratic.otherSeats>2.99,"Three non-caucusing independent contests stay distinct");
const close=check(project(all(0)));
const wider=check(project(all(0),{uncertaintyMultiplier:1.3}));
assert.notEqual(close.demSeats,wider.demSeats,"Changing uncertainty can change modeled expectations");
assert.equal(JSON.stringify(project(all(0))),JSON.stringify(close),"Deterministic reproducibility");
assert.throws(()=>project(all(1).slice(1)),/17-state/);
assert.throws(()=>project([...all(1).slice(1),{code:"ME",margin:NaN,sigma:5.2}]),/invalid/);
console.log("PASS: Senate control simulation conserves 100 seats, handles 3 independents, wide/standard assumptions, control probabilities and reproducibility");
